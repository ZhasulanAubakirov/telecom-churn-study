-- Учебные данные: одна строка — один клиент в начале месяца.
-- churned: 1 — ушёл за месяц, 0 — остался.
WITH customers (customer_id, tariff, churned) AS (
    VALUES
        (1, 'Базовый', 1), (2, 'Базовый', 1),
        (3, 'Базовый', 1), (4, 'Базовый', 1),
        (5, 'Базовый', 0), (6, 'Базовый', 0),
        (7, 'Базовый', 0), (8, 'Базовый', 0),
        (9, 'Базовый', 0), (10, 'Базовый', 0),
        (11, 'Базовый', 0), (12, 'Базовый', 0),
        (13, 'Базовый', 0), (14, 'Базовый', 0),
        (15, 'Базовый', 0), (16, 'Базовый', 0),
        (17, 'Базовый', 0), (18, 'Базовый', 0),
        (19, 'Базовый', 0), (20, 'Базовый', 0),
        (21, 'Премиум', 1), (22, 'Премиум', 1),
        (23, 'Премиум', 1), (24, 'Премиум', 0),
        (25, 'Премиум', 0), (26, 'Премиум', 0),
        (27, 'Премиум', 0), (28, 'Премиум', 0),
        (29, 'Премиум', 0), (30, 'Премиум', 0)
)
SELECT
    tariff,
    COUNT(*) AS total_clients,
    SUM(churned) AS churned_clients,
    ROUND(100.0 * SUM(churned) / COUNT(*), 2) AS churn_percent
FROM customers
GROUP BY tariff
ORDER BY tariff;

-- Результат: Базовый | 20 | 4 | 20.0
--            Премиум | 10 | 3 | 30.0
